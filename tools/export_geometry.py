"""Export geometry from the FreeCAD arm model for the host code.

By default this reads cad/arm/Arm.FCStd and writes host/include/arm/geometry.hpp
from the VarSet labelled "Kinematics". The header is generated; never hand-edit it.
Rerun this script after changing the CAD and commit both files.

    python3 tools/export_geometry.py                 # regenerate geometry.hpp
    python3 tools/export_geometry.py --varsets       # also dump every VarSet to a txt for reference
"""
import argparse
import sys
import zipfile
import xml.etree.ElementTree as ET
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DEFAULT_CAD = REPO / "cad" / "arm" / "Arm.FCStd"
DEFAULT_HEADER = REPO / "host" / "include" / "arm" / "geometry.hpp"
KINEMATICS_VARSET = "Kinematics"

UNITS = {
    "App::PropertyLength": "mm",
    "App::PropertyDistance": "mm",
    "App::PropertyAngle": "deg",
}


def format_value(prop):
    value = prop[0]
    if value.tag == "Float":
        text = f"{float(value.get('value')):.6f}".rstrip("0").rstrip(".")
    elif value.tag == "Bool":
        text = value.get("value")
    else:
        text = value.get("value", "")
    unit = UNITS.get(prop.get("type"))
    return f"{text} {unit}" if unit else text


def read_varsets(cad_path):
    """Yield (label, [property elements], {name: expression}) for each VarSet in the file."""
    with zipfile.ZipFile(cad_path) as z:
        root = ET.fromstring(z.read("Document.xml"))

    varset_names = [o.get("name") for o in root.find("Objects") if o.get("type") == "App::VarSet"]
    data = {o.get("name"): o for o in root.find("ObjectData")}

    for name in varset_names:
        props = data[name].find("Properties").findall("Property")
        label = next((p[0].get("value") for p in props if p.get("name") == "Label"), name)
        expressions = {
            e.get("path"): e.get("expression")
            for p in props if p.get("name") == "ExpressionEngine"
            for e in p.iter("Expression")
        }
        variables = [p for p in props if p.get("group") is not None]
        yield label, variables, expressions


def write_header(cad_path, out_path, varset=KINEMATICS_VARSET):
    """Dump every numeric property of one VarSet as a constexpr double in namespace arm::geometry."""
    for label, variables, expressions in read_varsets(cad_path):
        if label != varset:
            continue
        lines = [
            f'// GENERATED by tools/export_geometry.py from {cad_path.name}, VarSet "{varset}".',
            "// Do not edit by hand. Change the CAD, rerun the script, commit both. Units: mm.",
            "#pragma once",
            "",
            "namespace arm::geometry {",
        ]
        count = 0
        for prop in variables:
            name = prop.get("name")
            raw = prop[0].get("value")
            if prop[0].tag == "Bool" or raw is None:
                continue
            doc = prop.get("doc")
            expr = expressions.get(name)
            if doc:
                lines.append(f"    // {doc}")
            if expr:
                lines.append(f"    //   = {expr}")
            lines.append(f"    constexpr double {name} = {float(raw):.10g};")
            lines.append("")
            count += 1
        lines += ["}", ""]
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text("\n".join(lines), encoding="utf-8")
        print(f"Wrote {count} constants to {out_path}")
        return
    sys.exit(f"error: no VarSet labelled {varset!r} in {cad_path}")


def write_varsets_txt(cad_path, out_path):
    """Human-readable dump of every VarSet, for reference only."""
    lines = []
    for label, variables, expressions in read_varsets(cad_path):
        for prop in variables:
            name = prop.get("name")
            line = f"{label}.{name} = {format_value(prop)}"
            if name in expressions:
                line += f"  (= {expressions[name]})"
            if prop.get("doc"):
                line += f"  # {prop.get('doc')}"
            lines.append(line)
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(lines)} variables to {out_path}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cad", type=Path, default=DEFAULT_CAD, help="FreeCAD file to read")
    ap.add_argument("--header", type=Path, default=DEFAULT_HEADER, help="generated C++ header to write")
    ap.add_argument("--varset", default=KINEMATICS_VARSET, help="label of the VarSet to export")
    ap.add_argument("--varsets", nargs="?", const=True, default=None, metavar="TXT",
                    help="also dump all VarSets to a txt (default: <cad stem>_varsets.txt next to the header)")
    args = ap.parse_args()

    write_header(args.cad, args.header, args.varset)
    if args.varsets is not None:
        txt = args.header.parent / f"{args.cad.stem}_varsets.txt" if args.varsets is True else Path(args.varsets)
        write_varsets_txt(args.cad, txt)


if __name__ == "__main__":
    main()
